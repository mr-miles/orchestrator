"""OpenShell network policy and provider profile for reaching the controller.

The controller exposes two endpoints to sandboxes, on different ports because OpenShell does not
allow an MCP endpoint to share a host and port with another protocol:

* **MCP** (``protocol: mcp``, ``<mcp_port>/mcp``): the gateway parses every JSON-RPC request and
  allows only the MCP handshake methods and ``tools/call`` for the tools this controller serves
  (:data:`MCP_TOOLS`). Anything else is denied at the gateway before it reaches the controller.
* **git** (``protocol: rest``, ``<port>/git/<repo>.git``): smart-HTTP fetch; push
  (``git-receive-pack``) only for roles that may push. Verifiers get fetch only.

The same endpoints are declared in the workspace provider profile so the gateway injects the
SPIFFE-derived bearer into exactly these requests (see identity.py).
"""
from __future__ import annotations

from typing import Any
from urllib.parse import urlparse

import yaml

from .config import Config
from .store.mcp import STORE_TOOLS

WORKFLOW_TOOLS = ("whoami", "get_assignment", "verify_attestation", "progress", "report")
MCP_TOOLS = tuple(STORE_TOOLS) + WORKFLOW_TOOLS
MCP_VERSIONS = ["2025-06-18", "2025-11-25", "2026-07-28"]
MCP_METHODS = ["initialize", "notifications/initialized", "notifications/cancelled", "ping",
               "tools/list", "server/discover"]
GIT_BINARIES = ["/usr/bin/git", "/usr/lib/git-core/git-remote-http",
                "/usr/lib/git-core/git-remote-https"]
PROFILE_ID = "legion-controller"


def _host_port(url: str) -> tuple[str, int, str]:
    u = urlparse(url)
    return (u.hostname or "host.openshell.internal",
            u.port or (443 if u.scheme == "https" else 80), u.path or "/")


def mcp_endpoint(cfg: Config) -> dict[str, Any]:
    host, port, path = _host_port(cfg.server.mcp_url)
    return {
        "host": host, "port": port, "path": path, "protocol": "mcp", "enforcement": "enforce",
        "tls": "none" if cfg.server.mcp_url.startswith("http:") else "",
        "mcp": {"versions": MCP_VERSIONS},
        "rules": [{"allow": {"method": m}} for m in MCP_METHODS]
                 + [{"allow": {"method": "tools/call", "tool": {"any": list(MCP_TOOLS)}}}],
    }


def git_endpoint(cfg: Config, push: bool) -> dict[str, Any]:
    host, port, _ = _host_port(cfg.server.public_url)
    repo = f"/git/{cfg.repo.name}.git"
    rules = [{"allow": {"method": "GET", "path": f"{repo}/info/refs"}},
             {"allow": {"method": "POST", "path": f"{repo}/git-upload-pack"}}]
    deny = []
    if push:
        rules.append({"allow": {"method": "POST", "path": f"{repo}/git-receive-pack"}})
    else:
        deny.append({"method": "POST", "path": f"{repo}/git-receive-pack"})
    ep = {"host": host, "port": port, "path": f"{repo}/**", "protocol": "rest",
          "enforcement": "enforce", "tls": "none" if cfg.server.public_url.startswith("http:") else "",
          "rules": rules}
    if deny:
        ep["deny_rules"] = deny
    return ep


def network_policies(cfg: Config, *, agent: bool, push: bool) -> dict[str, Any]:
    pol: dict[str, Any] = {"legion_git": {"name": "legion-git", "endpoints": [git_endpoint(cfg, push)],
                                          "binaries": [{"path": b} for b in GIT_BINARIES]}}
    if agent:
        pol["legion_mcp"] = {"name": "legion-mcp", "endpoints": [mcp_endpoint(cfg)],
                             "binaries": [{"path": b} for b in cfg.sandbox.agent_binaries]}
    return pol


def render_policy(cfg: Config, template: str, *, agent: bool, push: bool) -> str:
    """Merge the controller endpoints into a sandbox policy template (static parts only)."""
    doc = yaml.safe_load(cfg.resolve(template).read_text()) or {}
    nets = doc.setdefault("network_policies", {}) or {}
    clash = {"legion_mcp", "legion_git"} & set(nets)
    if clash:
        raise ValueError(f"{template}: {sorted(clash)} are generated by the controller; remove them")
    nets.update(network_policies(cfg, agent=agent, push=push))
    doc["network_policies"] = nets
    return yaml.safe_dump(doc, sort_keys=False)


def provider_profile(cfg: Config) -> dict[str, Any]:
    """Workspace provider profile: SPIFFE token grant injected into controller requests only."""
    ic = cfg.identity
    base = cfg.server.public_url.rstrip("/")
    return {
        "id": PROFILE_ID,
        "display_name": "Legion orchestrator",
        "description": "Controller access (MCP + git) with a task-scoped token obtained from the "
                       "sandbox's SPIFFE JWT-SVID",
        "category": "other",
        "credentials": [{
            "name": "access_token",
            "description": "Short-lived controller token (client_credentials, jwt-spiffe assertion)",
            "required": False,
            "auth_style": "bearer",
            "header_name": "Authorization",
            "token_grant": {
                "grant_type": "client_credentials",
                "token_endpoint": f"{base}/oauth/token",
                "audience": ic.token_audience,
                "jwt_svid_audience": ic.svid_audience,
                "client_assertion_type": "urn:ietf:params:oauth:client-assertion-type:jwt-spiffe",
                "scopes": [ic.scope],
                "cache_ttl_seconds": max(30, min(ic.access_ttl_s // 2, 120)),
            },
        }],
        "endpoints": [mcp_endpoint(cfg), git_endpoint(cfg, push=True)],
        "binaries": list(dict.fromkeys(list(cfg.sandbox.agent_binaries) + GIT_BINARIES)),
    }


def setup_commands(cfg: Config, profile_file: str) -> list[list[str]]:
    """One-time workspace setup (not per sandbox)."""
    ob = cfg.sandbox.openshell_bin
    return [[ob, "profile", "import", "-f", profile_file],
            [ob, "provider", "create", "--name", cfg.identity.provider, "--type", PROFILE_ID,
             "--runtime-credentials"]]
