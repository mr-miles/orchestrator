"""Environment images: ``FROM <base>`` plus system packages and mise-installed tools.

Content-addressed: the tag is the hash of the Dockerfile and mise.toml, so the same recipe always
names the same image and building it again (another change, a retry, a restart) finds it.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field

MISE_DATA_DIR = "/usr/local/share/mise"     # under /usr: read-only in every sandbox policy
IMAGE_REPO = "legion-env"


@dataclass(frozen=True)
class Tool:
    """A tool as installed in an image: versions and binary paths resolved. The library's tool
    entry is the one place its binaries, settings and network needs are written."""
    name: str
    description: str
    mise: dict[str, str]
    apt: tuple[str, ...] = ()
    binaries: tuple[str, ...] = ()               # absolute paths (globs)
    env: tuple[tuple[str, str], ...] = ()        # baked into the image as ENV


def install_dir(tool_id: str) -> str:
    """Where mise installs a tool (any version): ``npm:prettier`` -> installs/npm-prettier/*."""
    safe = tool_id.replace(":", "-").replace("/", "-")
    return f"{MISE_DATA_DIR}/installs/{safe}/*"


def merged_env(tools: list[Tool]) -> tuple[dict[str, str], list[str]]:
    """The tools' environment variables merged, and conflicts (two tools, one name, two values)."""
    merged: dict[str, tuple[str, str]] = {}
    conflicts = []
    for t in tools:
        for k, v in t.env:
            if k in merged and merged[k][1] != v:
                conflicts.append(f"{k} is {merged[k][1]!r} in {merged[k][0]} but {v!r} in {t.name}")
            merged.setdefault(k, (t.name, v))
    return {k: v for k, (_, v) in merged.items()}, conflicts


def mise_toml(tools: list[Tool]) -> str:
    """The global mise config baked into the image (``/etc/mise/config.toml``)."""
    merged: dict[str, str] = {}
    for t in tools:
        merged.update(t.mise)
    return "\n".join(["# Generated by legion-orch from the approved environment spec.", "[tools]",
                      *(f"{json.dumps(k)} = {json.dumps(v)}" for k, v in sorted(merged.items()))]) + "\n"


def dockerfile(base: str, tools: list[Tool], mise_version: str, user: str) -> str:
    """Assumes a Debian/Ubuntu base (apt), like ``images/agent/Dockerfile``. Tools live in
    ``MISE_DATA_DIR`` (read-only at run time); mise's cache and state go to ``/tmp``, which every
    sandbox may write. Shims are on PATH, so ``python``, ``node``... resolve without activation.
    The tools' ``env`` comes after the install steps: it configures sandboxes, not the build."""
    apt = sorted({"ca-certificates", "curl", *(p for t in tools for p in t.apt)})
    env, _ = merged_env(tools)
    return "\n".join([
        "# Generated by legion-orch from the approved environment spec. Do not edit.",
        f"FROM {base}",
        "USER root",
        f"ENV MISE_DATA_DIR={MISE_DATA_DIR} MISE_CONFIG_DIR=/etc/mise \\",
        "    MISE_CACHE_DIR=/tmp/mise-cache MISE_STATE_DIR=/tmp/mise-state MISE_YES=1",
        f"ENV PATH={MISE_DATA_DIR}/shims:$PATH",
        "RUN apt-get update \\",
        f"    && apt-get install -y --no-install-recommends {' '.join(apt)} \\",
        "    && rm -rf /var/lib/apt/lists/*",
        f"RUN curl -fsSL https://mise.run | MISE_VERSION={mise_version} "
        "MISE_INSTALL_PATH=/usr/local/bin/mise sh \\",
        "    && mise --version",
        "COPY mise.toml /etc/mise/config.toml",
        "RUN mise install && mise reshim && mise ls \\",
        f"    && chmod -R a+rX {MISE_DATA_DIR} && rm -rf /tmp/mise-cache /tmp/mise-state",
        *(f"ENV {k}={json.dumps(v)}" for k, v in sorted(env.items())),
        f"USER {user}",
        "",
    ])


CHANGE_LABEL, RECIPE_LABEL = "org.legion.change", "org.legion.recipe"


def recipe_hash(files: dict[str, str]) -> str:
    """The build context's hash: the same recipe always has the same one."""
    h = hashlib.sha256()
    for k, v in sorted(files.items()):
        h.update(f"{k}\n{v}".encode() + b"\0")
    return h.hexdigest()[:16]


def image_tag(files: dict[str, str], registry: str | None, change: str) -> str:
    """One tag per change and recipe: roles of a change with the same recipe share it, and a
    change's images are its own to remove when it ends. Another change with the same recipe
    gets its own tag on the same layers (the build cache makes it nearly free)."""
    repo = f"{registry.rstrip('/')}/{IMAGE_REPO}" if registry else f"localhost/{IMAGE_REPO}"
    return f"{repo}:{change}-{recipe_hash(files)}"


@dataclass
class ImageRecipe:
    """What to build for one base image and tool set: the build context and its tag."""
    base: str
    tools: list[Tool]
    files: dict[str, str] = field(default_factory=dict)    # Dockerfile, mise.toml
    tag: str = ""
    labels: dict[str, str] = field(default_factory=dict)   # the change and the recipe hash

    @classmethod
    def make(cls, base: str, tools: list[Tool], *, mise_version: str, user: str,
             registry: str | None, change: str) -> ImageRecipe:
        files = {"Dockerfile": dockerfile(base, tools, mise_version, user),
                 "mise.toml": mise_toml(tools)}
        return cls(base=base, tools=tools, files=files, tag=image_tag(files, registry, change),
                   labels={CHANGE_LABEL: change, RECIPE_LABEL: recipe_hash(files)})
