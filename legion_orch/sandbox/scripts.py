"""Bootstrap scripts uploaded into sandboxes (they never contain credentials)."""

# Under OpenShell, requests to the controller are authenticated by the gateway (it injects the
# bearer); nothing here holds a credential. LEGION_ACCESS_TOKEN only exists with LocalRunner.
GIT_AUTH = r"""
git_auth() {
  if [ -n "${LEGION_ACCESS_TOKEN:-}" ]; then
    git -c http.extraHeader="Authorization: Bearer $LEGION_ACCESS_TOKEN" "$@"
  else
    git "$@"
  fi
}
"""

# Each script does one step, without decisions: the controller runs them in order, as separate
# steps, and chooses which (it knows whether the role pushes, whether the sandbox is reused,
# where a branch starts and whether a setup is pinned). They live in <sandbox root>/payload/.
_HEAD = r"""#!/usr/bin/env bash
set -euo pipefail
P="$(cd "$(dirname "$0")" && pwd)"; SB="$(dirname "$P")"   # <sandbox root>/payload/<script>
set -a; source "$P/run.env"; set +a
""" + GIT_AUTH

CLONE_SH = _HEAD + r"""
# Generated by legion-orch. Clone the repository into <sandbox root>/work: a partial clone –
# all history, file contents fetched when a command needs them.
git_auth clone --quiet --filter=blob:none --no-checkout "$LEGION_GIT_URL" "$SB/work"
# local development only: emulate the gateway's credential for the agent's own git calls
[ -z "${LEGION_ACCESS_TOKEN:-}" ] || \
  git -C "$SB/work" config http.extraHeader "Authorization: Bearer $LEGION_ACCESS_TOKEN"
"""

CHECKOUT_SH = _HEAD + r"""
# Generated by legion-orch. Check out commit $1, detached (no branch: nothing is committed here).
cd "$SB/work"
git_auth fetch --quiet --filter=blob:none origin "$1"
git checkout --quiet --detach "$1"
"""

BRANCH_SH = _HEAD + r"""
# Generated by legion-orch. Put the working copy on the run's branch $1 at commit $2, ready to
# commit and push (only the run's own branch may be pushed).
cd "$SB/work"
git config user.name "legion-$LEGION_ROLE"
git config user.email "$LEGION_RUN_ID@legion.local"
git_auth fetch --quiet --filter=blob:none origin "$2"
git checkout --quiet -B "$1" "$2"
"""

RUN_AGENT_SH = _HEAD + r"""
# Generated by legion-orch. Start the agent in <sandbox root>/work (checked out and set up by the
# controller's earlier steps): install the run's skills, continue the agent's session, exec.
mkdir -p "$SB/work"; cd "$SB/work"
export LEGION_PAYLOAD="$P" LEGION_MCP_CONFIG="$P/mcp.json"
# The run's skills, loaded on demand by the agent: replace any legion-* skills an earlier run in
# this sandbox installed (a payload without skills keeps them).
if [ -d "$P/skills" ]; then
  SKILLS="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/skills"
  mkdir -p "$SKILLS"
  rm -rf "$SKILLS"/legion-*
  cp -R "$P/skills/." "$SKILLS/"
  echo "[legion] installed $(ls "$P/skills" | wc -l | tr -d ' ') skills into $SKILLS"
fi
# A rework continues the earlier session (Claude Code keeps it under its config dir) if the
# sandbox still has it; otherwise the agent starts a new one.
if [ -n "${LEGION_RESUME_SESSION:-}" ]; then
  if find "${CLAUDE_CONFIG_DIR:-$HOME/.claude}/projects" -name "$LEGION_RESUME_SESSION.jsonl" \
       2>/dev/null | grep -q .; then
    echo "[legion] resuming agent session $LEGION_RESUME_SESSION"
  else
    if [ "${LEGION_REQUIRE_SESSION:-0}" = "1" ]; then
      echo "[legion] agent session $LEGION_RESUME_SESSION not found" >&2
      exit 3
    fi
    echo "[legion] agent session $LEGION_RESUME_SESSION not found; starting a new one"
    unset LEGION_RESUME_SESSION
  fi
fi
# local development only: emulate the gateway's credential for the a2a CLI (A2ACLI_AUTH: --auth)
[ -z "${LEGION_ACCESS_TOKEN:-}" ] || export A2ACLI_AUTH="Bearer $LEGION_ACCESS_TOKEN"
# A2A: register the change's AI Catalog (its agents' cards) with the a2a CLI, if the image has it
if [ -n "${LEGION_A2A_CATALOG:-}" ]; then
  if ! command -v a2a >/dev/null 2>&1; then
    echo "[legion] no a2a CLI on PATH: A2A catalog not registered"
  elif a2a catalog update legion >/dev/null 2>&1 \
       || a2a catalog add legion "$LEGION_A2A_CATALOG" >/dev/null 2>&1; then
    echo "[legion] registered A2A catalog legion ($LEGION_A2A_CATALOG)"
  else
    echo "[legion] could not register A2A catalog $LEGION_A2A_CATALOG" >&2
  fi
fi
echo "[legion] starting the agent in $PWD"
exec bash -lc "$LEGION_AGENT_COMMAND"
"""

MISE_SETUP_SH = r"""#!/usr/bin/env bash
# Generated by legion-orch. The repository's setup: mise.toml's `setup` task, only from the
# version the controller pinned ($1, G-MS1) – an agent's edit to it is never run. Run in the
# checkout.
set -euo pipefail
pin="$1"
got="$(git rev-parse HEAD:mise.toml 2>/dev/null || true)"
if [ "$got" != "$pin" ]; then
  echo "G-MS1: mise.toml at HEAD (${got:-missing}) is not the pinned version ($pin): setup not run" >&2
  exit 3
fi
export MISE_YES=1
mise trust --quiet mise.toml
exec mise run setup
"""


def payload_scripts() -> dict[str, str]:
    """The step scripts every payload carries (agent and verifier alike)."""
    return {"clone.sh": CLONE_SH, "checkout.sh": CHECKOUT_SH, "branch.sh": BRANCH_SH,
            "mise-setup.sh": MISE_SETUP_SH, "run-agent.sh": RUN_AGENT_SH}
