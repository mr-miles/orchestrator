"""Sandbox environments: images with mise-installed tools, network-policy provider profiles and
resource driver config, built by the controller after the environment spec is approved (H-E1).

Everything here is content-addressed so it composes and is reused: an image tag is the hash of
its Dockerfile and mise.toml, a provider profile id the hash of its body. Building the same
environment again (another change, a retry, a restart) finds the image or profile and skips it.

* :func:`mise_toml`, :func:`dockerfile`, :func:`image_tag` – the image recipe.
* :func:`network_profile` – a credentialless OpenShell provider profile for one network policy
  (attached providers contribute their endpoints to the sandbox's effective policy).
* :func:`driver_config` – resources rendered from ``policies/sandbox-resources.template.yaml``.
* :class:`EnvironmentBuilder` – where images and providers are made: :class:`PodmanBuilder`
  (podman + the openshell CLI) or :class:`NoBuilder` (local runner: default images, no providers).
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from ..config import Config
from .runner import openshell_cli
from .templates import base_values, render

MISE_DATA_DIR = "/usr/local/share/mise"     # under /usr: read-only in every sandbox policy
IMAGE_REPO = "legion-env"
NET_PREFIX = "legion-net-"


@dataclass(frozen=True)
class Tool:
    """A library tool (``environments/tools/<name>.yaml``) with its versions and binary paths
    resolved. The tool entry is the one place a tool's binaries are named; network policies
    refer to tools, not paths."""
    name: str
    description: str
    mise: dict[str, str]
    apt: tuple[str, ...] = ()
    binaries: tuple[str, ...] = ()               # absolute paths (globs)
    env: tuple[tuple[str, str], ...] = ()        # baked into the image as ENV


@dataclass(frozen=True)
class Policy:
    """A library network policy (``environments/policies/<name>.yaml``) as attached to one
    profile: ``binaries`` are those of the profile's tools that the policy serves."""
    name: str
    description: str
    endpoints: tuple[dict, ...]
    binaries: tuple[str, ...]
    tools: tuple[str, ...] = ()


def install_dir(tool_id: str) -> str:
    """Where mise installs a tool (any version): ``npm:prettier`` -> installs/npm-prettier/*."""
    safe = tool_id.replace(":", "-").replace("/", "-")
    return f"{MISE_DATA_DIR}/installs/{safe}/*"


def binary_paths(mise: dict[str, str], binaries: list[str]) -> tuple[tuple[str, ...], str | None]:
    """A tool's binaries as absolute paths: relative ones are under its single mise tool's
    install directory. Returns the paths and an error for an entry that cannot be resolved."""
    rel = [b for b in binaries if not b.startswith("/")]
    if rel and len(mise) != 1:
        return (), (f"relative binaries {rel} need exactly one mise tool to resolve against "
                    f"(this entry has {len(mise)}); use absolute paths")
    base = install_dir(next(iter(mise))) if rel else ""
    return tuple(b if b.startswith("/") else f"{base}/{b}" for b in binaries), None


@dataclass
class ImageRecipe:
    """What to build for one sandbox base image and tool set."""
    base: str
    tools: list[Tool]
    files: dict[str, str] = field(default_factory=dict)    # build context: Dockerfile, mise.toml
    tag: str = ""


def _digest(*parts: str) -> str:
    h = hashlib.sha256()
    for p in parts:
        h.update(p.encode() + b"\0")
    return h.hexdigest()


def mise_toml(tools: list[Tool]) -> str:
    """The global mise config baked into the image (``/etc/mise/config.toml``)."""
    lines = ["# Generated by legion-orch from the approved environment spec.", "[tools]"]
    merged: dict[str, str] = {}
    for t in tools:
        merged.update(t.mise)
    for tool_id, version in sorted(merged.items()):
        lines.append(f"{json.dumps(tool_id)} = {json.dumps(version)}")
    return "\n".join(lines) + "\n"


def dockerfile(base: str, tools: list[Tool], mise_version: str, user: str) -> str:
    """``FROM <base>`` plus system packages and mise-installed tools under ``/usr/local``.

    Assumes a Debian/Ubuntu base (apt), like ``images/agent/Dockerfile``. Tools live in
    ``MISE_DATA_DIR`` (read-only at run time); mise's cache and state go to ``/tmp``, which every
    sandbox may write. Shims are on PATH, so ``python``, ``node``... resolve without activation."""
    apt = sorted({"ca-certificates", "curl", *(p for t in tools for p in t.apt)})
    return "\n".join([
        "# Generated by legion-orch from the approved environment spec. Do not edit.",
        f"FROM {base}",
        "USER root",
        f"ENV MISE_DATA_DIR={MISE_DATA_DIR} MISE_CONFIG_DIR=/etc/mise \\",
        "    MISE_CACHE_DIR=/tmp/mise-cache MISE_STATE_DIR=/tmp/mise-state MISE_YES=1",
        f"ENV PATH={MISE_DATA_DIR}/shims:$PATH",
        "RUN apt-get update \\",
        f"    && apt-get install -y --no-install-recommends {' '.join(apt)} \\",
        "    && rm -rf /var/lib/apt/lists/*",
        f"RUN curl -fsSL https://mise.run | MISE_VERSION={mise_version} "
        "MISE_INSTALL_PATH=/usr/local/bin/mise sh \\",
        "    && mise --version",
        "COPY mise.toml /etc/mise/config.toml",
        "RUN mise install && mise reshim && mise ls \\",
        f"    && chmod -R a+rX {MISE_DATA_DIR} && rm -rf /tmp/mise-cache /tmp/mise-state",
        *_env_lines(tools),
        f"USER {user}",
        "",
    ])


def tool_env(tools: list[Tool]) -> tuple[dict[str, str], list[str]]:
    """The tools' environment variables merged, and conflicts (two tools, one name, two values)."""
    merged: dict[str, tuple[str, str]] = {}
    conflicts = []
    for t in tools:
        for k, v in t.env:
            if k in merged and merged[k][1] != v:
                conflicts.append(f"{k} is {merged[k][1]!r} in {merged[k][0]} but {v!r} in {t.name}")
            merged.setdefault(k, (t.name, v))
    return {k: v for k, (_, v) in merged.items()}, conflicts


def _env_lines(tools: list[Tool]) -> list[str]:
    """ENV after the install steps, so the tools' settings apply to sandboxes, not the build."""
    env, _ = tool_env(tools)
    return [f"ENV {k}={json.dumps(v)}" for k, v in sorted(env.items())]


def image_tag(files: dict[str, str], registry: str | None) -> str:
    """Content-addressed tag: the same recipe always names the same image."""
    digest = _digest(*(f"{k}\n{v}" for k, v in sorted(files.items())))[:16]
    repo = f"{registry.rstrip('/')}/{IMAGE_REPO}" if registry else f"localhost/{IMAGE_REPO}"
    return f"{repo}:{digest}"


def image_recipe(cfg: Config, base: str, tools: list[Tool]) -> ImageRecipe:
    env = cfg.environment
    assert env is not None
    r = ImageRecipe(base=base, tools=tools)
    r.files = {"Dockerfile": dockerfile(base, tools, env.mise_version, cfg.sandbox.run_as_user),
               "mise.toml": mise_toml(tools)}
    r.tag = image_tag(r.files, env.registry)
    return r


def network_profile(policy: Policy) -> dict[str, Any]:
    """A credentialless provider profile carrying one network policy. Its id is derived from the
    content, so an edited policy is a new profile and running sandboxes keep the old one."""
    body = {"display_name": f"legion network: {policy.name}", "description": policy.description,
            "category": "other", "credentials": [],
            "endpoints": [{"protocol": "rest", "enforcement": "enforce", "access": "read-only"} | e
                          for e in policy.endpoints],   # rest: inspected (TLS terminated)
            "binaries": list(policy.binaries)}
    pid = f"{NET_PREFIX}{policy.name}-{_digest(json.dumps(body, sort_keys=True))[:8]}"
    return {"id": pid} | body


def _drop_nulls(v: Any) -> Any:
    if isinstance(v, dict):
        out = {k: _drop_nulls(x) for k, x in v.items() if x is not None}
        return {k: x for k, x in out.items() if x not in ({}, [])}
    return v


def driver_config(cfg: Config, resources: dict[str, int] | None) -> str | None:
    """``--driver-config-json`` for a sandbox's resources (None: driver defaults)."""
    res = resources or {}
    if not res:
        return None
    doc = _drop_nulls(render(cfg, "sandbox_resources", base_values(cfg) | {
        "VCPUS": res.get("vcpus"), "MEMORY_MIB": res.get("memory_mib"),
        "DISK_MIB": res.get("disk_mib")}))
    return json.dumps(doc, sort_keys=True) if doc else None


# ---------------------------------------------------------------------------- builders
class BuildError(Exception):
    pass


class EnvironmentBuilder:
    """Makes images and network providers exist. Both operations are idempotent."""

    async def ensure_image(self, recipe: ImageRecipe) -> tuple[str | None, str]:
        """Build (or find) the image; return the reference sandboxes use (None: the runner's
        default image) and a log."""
        raise NotImplementedError

    async def ensure_provider(self, profile: dict[str, Any]) -> str:
        """Import the profile and create a provider of the same name unless they exist; return
        a log. The provider name is the profile id."""
        raise NotImplementedError


class NoBuilder(EnvironmentBuilder):
    """Local runner (development, no isolation): nothing to build or attach."""

    async def ensure_image(self, recipe):
        return None, f"local runner: {recipe.tag} not built (default image)\n"

    async def ensure_provider(self, profile):
        return f"local runner: provider {profile['id']} not created\n"


async def _run(argv: list[str], timeout: float) -> tuple[int, str]:
    proc = await asyncio.create_subprocess_exec(*argv, stdout=asyncio.subprocess.PIPE,
                                                stderr=asyncio.subprocess.STDOUT)
    try:
        out, _ = await asyncio.wait_for(proc.communicate(), timeout)
    except TimeoutError:
        proc.kill()
        await proc.wait()
        return 124, f"timeout after {timeout}s"
    return proc.returncode, out.decode(errors="replace")


class PodmanBuilder(EnvironmentBuilder):
    """Images with ``podman build`` on the controller host (and ``podman push`` when
    ``environment.registry`` is set); providers with the openshell CLI in ``sandbox.workspace``."""

    def __init__(self, cfg: Config):
        assert cfg.environment is not None
        self.cfg, self.env = cfg, cfg.environment
        self.cli = openshell_cli(cfg)

    async def _step(self, log: list[str], argv: list[str], timeout: float = 600,
                    probe: bool = False) -> int:
        log.append("$ " + " ".join(argv))
        rc, out = await _run(argv, timeout)
        log.append(out.rstrip()[-20000:])
        if rc != 0 and not probe:
            raise BuildError(f"{' '.join(argv[:3])} failed ({rc}): {out.strip()[-1500:]}\n"
                             + "\n".join(log)[-4000:])
        return rc

    async def ensure_image(self, recipe):
        if not recipe.base:
            raise BuildError("environment images are built FROM sandbox.image (agents) and "
                             "sandbox.verifier_image (verifier); set them in the config")
        log: list[str] = []
        pod = self.env.podman_bin
        if await self._step(log, [pod, "image", "exists", recipe.tag], probe=True) == 0:
            log.append(f"{recipe.tag} exists; reused")
            return recipe.tag, "\n".join(log)
        with tempfile.TemporaryDirectory(prefix="legion-env-") as ctx:
            for name, text in recipe.files.items():
                (Path(ctx) / name).write_text(text)
            await self._step(log, [pod, "build", "--pull=newer", "-t", recipe.tag, ctx],
                             timeout=self.env.build_timeout_s)
        if self.env.registry:
            await self._step(log, [pod, "push", recipe.tag], timeout=self.env.build_timeout_s)
        return recipe.tag, "\n".join(log)

    async def ensure_provider(self, profile):
        log: list[str] = []
        pid = profile["id"]
        if await self._step(log, [*self.cli, "profile", "export", pid, "-o", "json"], probe=True) != 0:
            with tempfile.NamedTemporaryFile("w", suffix=".yaml", delete=False) as f:
                yaml.safe_dump(profile, f, sort_keys=False)
            try:
                await self._step(log, [*self.cli, "profile", "import", "-f", f.name])
            finally:
                Path(f.name).unlink(missing_ok=True)
        else:
            log.append(f"profile {pid} exists; kept (content-addressed)")
        if await self._step(log, [*self.cli, "provider", "get", pid], probe=True) != 0:
            await self._step(log, [*self.cli, "provider", "create", "--name", pid, "--type", pid])
        else:
            log.append(f"provider {pid} exists; kept")
        return "\n".join(log)


def make_builder(cfg: Config) -> EnvironmentBuilder:
    return PodmanBuilder(cfg) if cfg.sandbox.runner == "openshell" and cfg.environment else NoBuilder()
