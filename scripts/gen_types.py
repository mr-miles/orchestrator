"""The web UI's API types, generated from the backend's pydantic models: their JSON Schema
(serialisation mode – what the API sends) as TypeScript. Writes frontend/src/lib/api.gen.ts,
which is not committed: `mise run ui:types` makes it (ui:check and ui:build run it first).

Only records the API sends as they are are generated; view-shaped dicts (server/views.py) keep
their hand-written types in lib/types.ts."""
from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from legion_orch.workflow import model
from legion_orch.workflow.attention import AttentionItem
from legion_orch.workflow.governance.attestations import GateAttestation
from legion_orch.workflow.results import ActionResult
from legion_orch.workflow.traceability import Traceability

OUT = Path(__file__).resolve().parent.parent / "frontend/src/lib/api.gen.ts"

# the records the UI reads (their nested records come with them)
MODELS = [model.Change, model.Node, model.Run, model.AgentQuestion, ActionResult, AttentionItem,
          GateAttestation, Traceability]
# the UI's names for records named otherwise in the backend
ALIASES = {"Risk": "RiskAssessment"}


def ts(s: dict) -> str:
    """A JSON Schema as a TypeScript type."""
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts(x) for x in s["anyOf"]))
    t = s.get("type")
    if t == "array":
        item = ts(s.get("items", {}))
        return f"({item})[]" if "|" in item else f"{item}[]"
    if t == "object":
        extra = s.get("additionalProperties")
        if "properties" in s:
            return "{ " + "; ".join(field(k, v, s) for k, v in s["properties"].items()) + " }"
        return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(t, "unknown")


def field(name: str, s: dict, parent: dict) -> str:
    """A property: always sent if required or defaulted (the API serialises every field)."""
    sent = name in parent.get("required", ()) or "default" in s
    return f"{name}{'' if sent else '?'}: {ts(s)}"


def declaration(name: str, s: dict) -> str:
    doc = f"/** {' '.join(s['description'].split())} */\n" if s.get("description") else ""
    if s.get("type") == "object" and "properties" in s:
        body = "".join(f"  {field(k, v, s)}\n" for k, v in s["properties"].items())
        return f"{doc}export interface {name} {{\n{body}}}\n"
    return f"{doc}export type {name} = {ts(s)}\n"


def defaults(name: str, s: dict) -> str:
    """``<Name>Defaults``: the record's schema defaults, for building one (test fixtures)."""
    props = {k: v["default"] for k, v in s.get("properties", {}).items() if "default" in v}
    if not props:
        return ""
    keys = " | ".join(json.dumps(k) for k in props)
    return (f"export const {name}Defaults: Pick<{name}, {keys}> = "
            f"{json.dumps(props, indent=2)}\n")


def main() -> None:
    _, schema = models_json_schema([(m, "serialization") for m in MODELS],
                                   ref_template="#/$defs/{model}")
    defs = schema["$defs"]
    out = ["// Generated by scripts/gen_types.py from the backend's models: do not edit.\n"]
    out += [declaration(n, defs[n]) for n in sorted(defs)]
    out += [d for n in sorted(defs) if (d := defaults(n, defs[n]))]
    out += [f"export type {ui} = {backend}\n" for ui, backend in ALIASES.items()]
    OUT.write_text("\n".join(out))
    print(OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT, file=sys.stderr)


if __name__ == "__main__":
    main()
